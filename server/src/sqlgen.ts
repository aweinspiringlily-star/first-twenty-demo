// Generates the DDL for record tables from the shared collection list (src/sync/collections.ts), so the
// table names always match tableName(). Used once to write server/sql/001_init.sql; collections added
// later get their tables from a new numbered migration (`npm run server:gen-sql` prints the missing DDL).
// 001 created version columns as integer; 002 made them bigint (the change_log seq of each write), and
// new tables are generated with bigint directly.
import { RECORD_COLLECTIONS, type RecordCollection, tableName } from '../../src/sync/collections'

export const WORKSPACE_ID = 'default'

/** One table per record collection: (workspace_id, id, data jsonb, version, pos, updated_at, updated_by). */
export function recordTableSql(collection: RecordCollection, versionType: 'integer' | 'bigint' = 'bigint'): string {
  const t = tableName(collection)
  return [
    `-- ${collection}`,
    `CREATE TABLE ${t} (`,
    `  workspace_id text NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,`,
    `  id text NOT NULL,`,
    `  data jsonb NOT NULL,`,
    `  version ${versionType} NOT NULL CHECK (version > 0),`,
    `  pos bigint NOT NULL DEFAULT 0,`,
    `  updated_at timestamptz NOT NULL DEFAULT now(),`,
    `  updated_by uuid NULL REFERENCES users (id) ON DELETE SET NULL,`,
    `  PRIMARY KEY (workspace_id, id)`,
    `);`,
    `CREATE INDEX ${t}_pos_idx ON ${t} (workspace_id, pos);`,
  ].join('\n')
}

const HEADER = `-- 001_init: the First Twenty schema (docs/SYNC.md).
-- Generated by \`npm run server:gen-sql -- --init\` from src/sync/collections.ts, then committed.
-- Never edit a migration that has been applied anywhere: add server/sql/002_*.sql instead.
-- Requires Postgres 13+ (gen_random_uuid() is built in).`

const CORE = `-- One workspace per server for now ('default').
CREATE TABLE workspaces (
  id text PRIMARY KEY,
  name text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  -- Set by the first PUT /api/workspace; GET /api/workspace is 404 'empty' until then.
  initialized_at timestamptz NULL,
  replaced_at timestamptz NULL,
  -- Highest change_log seq written for this workspace (updated in the same transaction as each write).
  last_seq bigint NOT NULL DEFAULT 0,
  -- seq at the end of the last full replace: clients whose since is older must resync.
  reset_seq bigint NOT NULL DEFAULT 0,
  -- Highest seq removed by pruning: clients whose since is older must resync.
  pruned_seq bigint NOT NULL DEFAULT 0
);
INSERT INTO workspaces (id, name) VALUES ('${WORKSPACE_ID}', 'Default workspace');

-- Logins. One admin for now; role leaves room for team logins with server-enforced roles later.
CREATE TABLE users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE CHECK (email = lower(email) AND length(email) BETWEEN 3 AND 254),
  password_hash text NOT NULL,
  role text NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'manager', 'employee')),
  created_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz NULL
);

-- Sessions: only the SHA-256 of the cookie token is stored.
CREATE TABLE sessions (
  token_hash text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  ip text NULL,
  user_agent text NULL
);
CREATE INDEX sessions_user_idx ON sessions (user_id);
CREATE INDEX sessions_expires_idx ON sessions (expires_at);

-- Single documents (meta, company, equity, complianceStatus, inboxState, settings).
CREATE TABLE workspace_docs (
  workspace_id text NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
  key text NOT NULL,
  data jsonb NOT NULL,
  version integer NOT NULL CHECK (version > 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid NULL REFERENCES users (id) ON DELETE SET NULL,
  PRIMARY KEY (workspace_id, key)
);`

const CHANGE_LOG = `-- Every accepted write appends a row; pulls read it. Rows older than 120 days may be pruned.
CREATE TABLE change_log (
  seq bigserial PRIMARY KEY,
  workspace_id text NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
  collection text NOT NULL,
  record_id text NOT NULL,
  op text NOT NULL CHECK (op IN ('upsert', 'delete')),
  version integer NOT NULL,
  data jsonb NULL,
  at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NULL REFERENCES users (id) ON DELETE SET NULL
);
CREATE INDEX change_log_workspace_seq_idx ON change_log (workspace_id, seq);
CREATE INDEX change_log_record_idx ON change_log (workspace_id, collection, record_id, seq);
CREATE INDEX change_log_at_idx ON change_log (at);`

/** The full text of server/sql/001_init.sql for the current collection list (as first written: integer versions). */
export function initSql(collections: readonly RecordCollection[] = RECORD_COLLECTIONS): string {
  return [
    HEADER,
    CORE,
    '-- Record collections: one table each, named snake_case of the DB key.',
    ...collections.map((c) => recordTableSql(c, 'integer')),
    CHANGE_LOG,
  ].join('\n\n') + '\n'
}

/** Names of the tables a migration file creates (CREATE TABLE [IF NOT EXISTS] name). */
export function tablesCreatedBy(sql: string): string[] {
  const out: string[] = []
  const re = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?"?([a-z_][a-z0-9_]*)"?\s*\(/gi
  for (let m = re.exec(sql); m; m = re.exec(sql)) out.push(m[1].toLowerCase())
  return out
}
